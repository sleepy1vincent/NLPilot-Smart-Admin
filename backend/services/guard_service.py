"""幻觉防护：只判断"这次有没有真的执行"，不判断"模型说了什么"。

为什么不再做文本判别
--------------------
v3.0 早期用约 190 条规则判断模型是否"声称完成"：
    CLAIM_PATTERNS（10 条）· SAFE_HINTS（22 条）· SMALLTALK_RE（30 分支）
    DENIAL_RE（20 分支）· CLARIFY_RE（16 分支）· RESULT_RE（12 分支）

实测暴露三个问题：
  1. 换个说法就漏："已删除" → "已经帮你删掉了" → "帮你删好了" …… 补不完
  2. 换成 7B 当审核员更差：无证据 45%（全判 pass）、带证据仅 55%，
     且对提示词措辞高度敏感（同一批用例，换个措辞从 0/6 变成 3/6）
  3. 正则在这批用例上 91%，但那是"背题"，换一批数据就会掉

结论：**真伪判断是语义任务，不该由规则承担；也不该再让模型自己判。**

现在的做法：把"记账权"从模型手里拿走
------------------------------------
  1. 副作用只能通过工具发生（模型不调工具，数据库就不会变）
  2. 操作结果只能由工具返回值陈述（含 rowcount）
  3. 没有工具调用 ⇒ 本次没有任何数据库操作（这是 tool_calls 为空的直接推论）

前端把这两个通道分开渲染（结果卡片 / 对话气泡 + "未执行"标记），
用户能对照 —— 谎言活不下去，不是因为模型变诚实了，
而是因为它旁边永远摆着账本。

返回协议（inspect）
------------------
    {"executed": True,  "tool": "query_products", "reason": "..."}
        模型调用了工具 → 结果以工具返回值为准

    {"executed": False, "tool": None, "reason": "..."}
        没调用工具 → 本次没有任何数据库操作（对话通道）

注意：这里**不看文本内容**，只看 `tool` 字段是否存在。
"""


def inspect(call: dict) -> dict:
    """判断"这次到底有没有执行"。

    参数
      call: nlu_service.recognize 的返回

    返回
      {"executed": bool, "tool": str|None, "reason": str}
    """
    tool = call.get("tool")
    if tool:
        return {
            "executed": True,
            "tool": tool,
            "reason": f"模型调用了工具 {tool}，结果以工具返回值为准",
        }
    return {
        "executed": False,
        "tool": None,
        "reason": "模型没有调用任何工具，本次未发生任何数据库操作",
    }
